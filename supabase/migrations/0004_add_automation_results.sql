-- Durable record of what the automated screening actually found, so the
-- app itself (Automation tab) can show recent SETUP results even if the
-- user never taps the push notification / that CCR session is gone.
-- Purely additive — unrelated to journal or automation_settings. Rollback:
-- drop table automation_results;
create table if not exists automation_results (
  id bigint generated by default as identity primary key,
  ticked_at timestamptz not null default now(),
  strategy text not null,
  index_name text not null,
  ticker text not null,
  score numeric,
  last_close numeric,
  phase text,
  entry_low numeric,
  entry_high numeric,
  stop_loss numeric,
  target numeric,
  rrr numeric,
  risk_pct numeric,
  action text,
  lots int,
  shares int,
  loss_at_stop_rp numeric,
  profit_at_target_rp numeric,
  narrative_markdown text
);

create index if not exists automation_results_ticked_at_idx
  on automation_results (ticked_at desc);
